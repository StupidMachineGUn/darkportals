CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  salt TEXT NOT NULL,
  hash TEXT NOT NULL,
  created_at TIMESTAMP DEFAULT now()
);
CREATE TABLE IF NOT EXISTS characters (
  user_id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  data TEXT NOT NULL,
  schema_v INTEGER NOT NULL DEFAULT 1,
  updated_at TIMESTAMP DEFAULT now()
);
CREATE TABLE IF NOT EXISTS heroes (
  name TEXT PRIMARY KEY,
  score INTEGER NOT NULL,
  data TEXT NOT NULL,
  at TIMESTAMP DEFAULT now()
);
CREATE TABLE IF NOT EXISTS jails (
  user_id INTEGER PRIMARY KEY,
  left_n INTEGER NOT NULL,
  total INTEGER NOT NULL,
  reason TEXT NOT NULL DEFAULT '',
  by TEXT NOT NULL DEFAULT '',
  at TIMESTAMP DEFAULT now()
);
ALTER TABLE characters ADD COLUMN IF NOT EXISTS ver INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS ip TEXT NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS settings (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS admin_log (id SERIAL PRIMARY KEY, at TIMESTAMP DEFAULT now(), admin TEXT NOT NULL, action TEXT NOT NULL, target TEXT, info TEXT);
CREATE TABLE IF NOT EXISTS auctions (id SERIAL PRIMARY KEY, seller INTEGER NOT NULL, seller_n TEXT NOT NULL, item TEXT NOT NULL, cur INTEGER NOT NULL, bidder INTEGER, bidder_n TEXT, buy INTEGER NOT NULL DEFAULT 0, exp BIGINT NOT NULL, done INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS mail (id SERIAL PRIMARY KEY, uid INTEGER NOT NULL, kind TEXT NOT NULL, msg TEXT NOT NULL DEFAULT '', gold INTEGER NOT NULL DEFAULT 0, item TEXT, ts BIGINT NOT NULL, claimed INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS ledger (id SERIAL PRIMARY KEY, uid INTEGER, ts BIGINT NOT NULL, kind TEXT NOT NULL, gold INTEGER NOT NULL DEFAULT 0, info TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS item_reg (u TEXT PRIMARY KEY, uid INTEGER NOT NULL, iid TEXT NOT NULL, ts BIGINT NOT NULL);
